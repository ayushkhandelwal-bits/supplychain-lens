"""Forecast model comparison: one table, one chosen model, honest statistics.

Selection rule: the model with the lowest **validation** WAPE is selected for inference.
The test quarter (Q4 2025) is reported for every model but never used to choose — choosing
on test would leak the answer into the decision.

Significance: a paired bootstrap over series gives a 95% interval for the WAPE difference
between the selected model and each other model on the test quarter.

    python -m supplychain_lens.evaluation.forecast_report
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from supplychain_lens.config import get_settings
from supplychain_lens.evaluation.metrics import by_group, forecast_summary, horizon_bucket
from supplychain_lens.features.forecasting import load_panel
from supplychain_lens.serving import registry

FORECAST_RUNS = {"forecast_baselines": None, "forecast_lstm": "LSTM (PyTorch)", "forecast_tft": "TFT (PyTorch)"}
SERVABLE = {"LSTM (PyTorch)": "forecast_lstm", "TFT (PyTorch)": "forecast_tft",
            "LightGBM (quantile)": "forecast_baselines"}


def load_predictions() -> tuple[pd.DataFrame, dict]:
    frames, versions = [], {}
    for name in FORECAST_RUNS:
        run = registry.load_run(name)
        if run is None:
            continue
        frames.append(pd.read_parquet(run.file("predictions.parquet")))
        versions[name] = run.version
    if not frames:
        raise FileNotFoundError("No forecast artifacts found. Train the baselines and models first.")
    return pd.concat(frames, ignore_index=True), versions


def bootstrap_wape_diff(a: pd.DataFrame, b: pd.DataFrame, n_boot: int = 1000, seed: int = 42) -> dict:
    """Paired bootstrap over series of WAPE(a) − WAPE(b). Negative = a is better."""
    ga = a.groupby("series").apply(lambda g: pd.Series({"err": (g.y - g.p50).abs().sum(), "vol": g.y.sum()}), include_groups=False)
    gb = b.groupby("series").apply(lambda g: pd.Series({"err": (g.y - g.p50).abs().sum()}), include_groups=False)
    ea, eb, vol = ga.err.to_numpy(), gb.err.loc[ga.index].to_numpy(), ga.vol.to_numpy()
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(ea), (n_boot, len(ea)))
    diffs = (ea[idx].sum(1) - eb[idx].sum(1)) / vol[idx].sum(1)
    point = (ea.sum() - eb.sum()) / vol.sum()
    lo, hi = np.quantile(diffs, [0.025, 0.975])
    return {"diff": float(point), "ci_low": float(lo), "ci_high": float(hi), "significant": bool(hi < 0 or lo > 0)}


def build() -> dict:
    s = get_settings()
    panel = load_panel()
    preds, versions = load_predictions()
    preds = preds.merge(panel.keys[["category"]].reset_index(names="series"), on="series")
    preds["date"] = panel.dates[preds.t_idx.to_numpy()]
    test = preds[preds.split == "test"].copy()
    test["bucket"] = horizon_bucket(test.h)

    overall = {m: {sp: forecast_summary(g) for sp, g in gm.groupby("split")} for m, gm in preds.groupby("model")}
    servable = {m: v for m, v in overall.items() if m in SERVABLE}
    selected = min(servable, key=lambda m: servable[m]["val"]["wape"])
    peak = test[(test.date >= "2025-11-24") & (test.date <= "2025-12-01")]
    result = {
        "selected_model": selected, "selected_artifact": SERVABLE[selected],
        "selection_rule": "lowest validation WAPE among servable models",
        "versions": versions, "overall": overall,
        "by_horizon_test": {m: by_group(g, "bucket").set_index("bucket").wape.to_dict() for m, g in test.groupby("model")},
        "by_category_test": {m: by_group(g, "category").set_index("category").wape.to_dict() for m, g in test.groupby("model")},
        "peak_week_test": {m: forecast_summary(g) for m, g in peak.groupby("model")},
        "bootstrap_vs_selected": {m: bootstrap_wape_diff(test[test.model == selected], g)
                                  for m, g in test.groupby("model") if m != selected},
        "split": {"train_end": str(s.train_end), "val_end": str(s.val_end), "test_start": str(s.test_start)},
    }
    return result


def render(r: dict) -> str:
    order = sorted(r["overall"], key=lambda m: r["overall"][m]["val"]["wape"])
    lines = ["# Forecast model comparison", "",
             "Generated by `python -m supplychain_lens.evaluation.forecast_report`. **Synthetic data** "
             "(NEXUS-SCCT data model). Every number below comes from a stored training run.", "",
             f"Split: train ≤ {r['split']['train_end']} · validation ≤ {r['split']['val_end']} · test from "
             f"{r['split']['test_start']} (3 origins × 400 series × 28 days).", "",
             f"**Selected for inference: {r['selected_model']}** — {r['selection_rule']}.", "",
             "| Model | Val WAPE | Test WAPE | Test MAE | Test RMSE | Test bias | Test P10–P90 coverage | Test pinball (scaled) |",
             "|---|---|---|---|---|---|---|---|"]
    for m in order:
        v, t = r["overall"][m]["val"], r["overall"][m]["test"]
        cov = f"{t['coverage_p10_p90']:.1%}" if "coverage_p10_p90" in t else "—"
        pin = f"{t['pinball_scaled']:.4f}" if "pinball_scaled" in t else "—"
        lines.append(f"| {m} | {v['wape']:.3f} | {t['wape']:.3f} | {t['mae']:.1f} | {t['rmse']:.1f} | "
                     f"{t['bias']:+.3f} | {cov} | {pin} |")
    lines += ["", "## Is the selected model really better? (test, paired bootstrap over series)", "",
              f"WAPE({r['selected_model']}) − WAPE(other); negative means the selected model is better.", "",
              "| Compared with | Difference | 95% interval | Clear difference? |", "|---|---|---|---|"]
    for m, d in r["bootstrap_vs_selected"].items():
        lines.append(f"| {m} | {d['diff']:+.4f} | [{d['ci_low']:+.4f}, {d['ci_high']:+.4f}] | {'yes' if d['significant'] else 'no'} |")
    lines += ["", "## Test WAPE by horizon", "", "| Model | " + " | ".join(next(iter(r["by_horizon_test"].values())).keys()) + " |",
              "|---" * (1 + len(next(iter(r["by_horizon_test"].values())))) + "|"]
    for m in order:
        lines.append(f"| {m} | " + " | ".join(f"{x:.3f}" for x in r["by_horizon_test"][m].values()) + " |")
    lines += ["", "## Peak week (24 Nov – 1 Dec 2025, includes Black Friday and Cyber Monday)", "",
              "| Model | WAPE | Bias |", "|---|---|---|"]
    for m in order:
        p = r["peak_week_test"][m]
        lines.append(f"| {m} | {p['wape']:.3f} | {p['bias']:+.3f} |")
    cats = list(next(iter(r["by_category_test"].values())).keys())
    lines += ["", "## Test WAPE by category", "", "| Model | " + " | ".join(cats) + " |", "|---" * (1 + len(cats)) + "|"]
    for m in order:
        lines.append(f"| {m} | " + " | ".join(f"{r['by_category_test'][m][c]:.3f}" for c in cats) + " |")
    lines += ["", "## Notes", "",
              "- WAPE = Σ|actual − forecast| / Σ actual. Bias > 0 means over-forecasting.",
              "- Coverage is the share of actual values inside the P10–P90 band; a calibrated band covers about 80%.",
              "- Seasonal naive and Holt-Winters produce point forecasts only.",
              "- Results are on synthetic data and are not evidence of real-world accuracy."]
    return "\n".join(lines) + "\n"


def main() -> None:
    s = get_settings()
    r = build()
    run = registry.start_run("forecast_comparison")
    registry.write_json(run, "comparison.json", r)
    registry.finalize(run)
    s.reports_dir.mkdir(exist_ok=True)
    (s.reports_dir / "forecast_comparison.md").write_text(render(r), encoding="utf-8")
    print(f"Selected: {r['selected_model']}  ->  reports/forecast_comparison.md")


if __name__ == "__main__":
    main()
