"""Business-impact experiment: baseline policy vs AI-assisted policy on the test quarter.

    python -m supplychain_lens.simulation.experiment

Design
  • period: Q4 2025 (the held-out test quarter), starting from the ACTUAL network state on 30 Sep
  • demand: the ACTUAL daily demand that occurred (the same for both policies)
  • world: digital twin (supplychain_lens/simulation/twin.py) — supplier delays resampled from each
    supplier's recent history, recorded disruptions cut capacity and add lead time
  • replications: 30, with common random numbers (both policies see identical delay draws)
  • decision inputs available to the AI policy each day: rolling forecasts from the selected model
    (origin = that day) and the risk classifier's score for that day — nothing from the future
  • statistics: paired differences per replication, mean with a 95% t-interval, and a paired
    t-test; every result is labelled SIMULATED
  • twin calibration: the baseline policy replayed in the twin is compared with what actually
    happened in the history (which was generated by the same baseline rule)
"""

from __future__ import annotations

import time

import numpy as np
import pandas as pd
from scipy import stats

from supplychain_lens.config import get_settings
from supplychain_lens.features.forecasting import load_panel
from supplychain_lens.features.risk import build_risk_panel
from supplychain_lens.serving import registry
from supplychain_lens.serving.forecaster import Forecaster
from supplychain_lens.serving.risk import RiskScorer
from supplychain_lens.simulation.twin import build_state, simulate

REPS = 30
METRICS = ["fill_rate", "stockout_rate", "lost_revenue", "lost_margin", "holding_cost", "ordering_cost",
           "backup_premium", "overflow_cost", "total_cost", "avg_inventory_value", "backup_orders"]


def paired_stats(a: np.ndarray, b: np.ndarray) -> dict:
    """b − a (AI minus baseline) with a 95% t-interval and paired t-test."""
    d = np.asarray(b, float) - np.asarray(a, float)
    n = len(d)
    se = d.std(ddof=1) / np.sqrt(n) if n > 1 else 0.0
    half = stats.t.ppf(0.975, n - 1) * se if se > 0 else 0.0
    p = float(stats.ttest_rel(b, a).pvalue) if se > 0 else float("nan")
    return {"baseline_mean": float(np.mean(a)), "ai_mean": float(np.mean(b)), "diff": float(d.mean()),
            "ci_low": float(d.mean() - half), "ci_high": float(d.mean() + half), "p_value": p,
            "relative_change": float(d.mean() / np.mean(a)) if np.mean(a) else float("nan")}


def run(reps: int = REPS, log=print) -> registry.Run:
    s = get_settings()
    t0 = time.perf_counter()
    panel = load_panel()
    start_idx = panel.val_end_idx + 1
    days = len(panel.dates) - start_idx
    state = build_state(panel.dates[start_idx], days, known_arrivals=True)
    order = state.keys[["sku_id", "warehouse_id"]].merge(panel.keys[["sku_id", "warehouse_id"]].reset_index(names="pi"),
                                                         on=["sku_id", "warehouse_id"]).pi.to_numpy()
    actual = panel.y[order][:, start_idx:]
    demand = np.repeat(actual[None], reps, axis=0)

    fc = Forecaster.load(panel=panel)
    log(f"  rolling forecasts with {fc.model_name} for {days} origins …")
    q = fc.predict(list(range(start_idx, start_idx + days)))[:, order]       # (days, S, H, 3)

    scorer = RiskScorer.load()
    rp = build_risk_panel()
    sup_order = [list(rp.suppliers.supplier_id).index(x) for x in state.supplier_ids]
    risk = np.stack([scorer.score(rp.X[sup_order, start_idx + t]) for t in range(days)])  # (days, n_sup)

    log(f"  simulating {reps} replications × 2 policies …")
    base = simulate(state, demand, "baseline", seed=s.seed)
    ai = simulate(state, demand, "ai", forecasts=q, risk=risk, risk_threshold=scorer.threshold, seed=s.seed)
    results = {m: paired_stats(base["per_rep"][m], ai["per_rep"][m]) for m in METRICS}
    # Ablation: forecast-driven ordering only (no risk-based backup switching) -> what the forecasts alone contribute.
    fc_only = simulate(state, demand, "ai", forecasts=q, risk=None, risk_threshold=1.0, seed=s.seed)
    # (recorded disruptions still trigger switching; predicted risk does not)
    ablation = {m: paired_stats(base["per_rep"][m], fc_only["per_rep"][m]) for m in METRICS}

    # Twin calibration: baseline replay vs recorded history (same rule generated the history).
    d = pd.read_parquet(s.data_dir / "nexus_v2" / "demand_daily.parquet", filters=[("date", ">=", panel.dates[start_idx])])
    hist_fill = float(d.sales_units.sum() / d.demand_units.sum())
    hist_stockout = float((d.lost_sales_units > 0).mean())
    calibration = {"history_fill_rate": hist_fill, "twin_baseline_fill_rate": results["fill_rate"]["baseline_mean"],
                   "history_stockout_rate": hist_stockout, "twin_baseline_stockout_rate": results["stockout_rate"]["baseline_mean"]}

    daily = pd.DataFrame({"date": pd.date_range(panel.dates[start_idx], periods=days),
                          "baseline_fill_rate": base["daily"]["fill_rate"], "ai_fill_rate": ai["daily"]["fill_rate"],
                          "baseline_lost_revenue": base["daily"]["lost_revenue"], "ai_lost_revenue": ai["daily"]["lost_revenue"],
                          "baseline_inventory_value": base["daily"]["inventory_value"], "ai_inventory_value": ai["daily"]["inventory_value"]})
    per_rep = pd.DataFrame({**{f"baseline_{m}": base["per_rep"][m] for m in METRICS}, **{f"ai_{m}": ai["per_rep"][m] for m in METRICS}})

    run_ = registry.start_run("business_impact")
    registry.write_json(run_, "results.json", {
        "label": "SIMULATED / POC RESULT — synthetic data, digital-twin replay; not real company results",
        "period": {"start": str(panel.dates[start_idx].date()), "end": str(panel.dates[-1].date()), "days": days},
        "replications": reps, "forecast_model": fc.model_name, "forecast_version": fc.version,
        "risk_model": scorer.selected, "risk_threshold": scorer.threshold, "metrics": results,
        "ablation_no_predicted_risk_switching": ablation,
        "uncertainty_note": "Replications vary supplier delays only; demand is the actual Q4 2025 history, so the intervals "
                            "reflect lead-time randomness, not demand uncertainty.",
        "twin_calibration": calibration, "seconds": round(time.perf_counter() - t0, 1),
        "assumptions": {"holding_rate_per_year": 0.25, "order_cost_usd": 500, "backup_premium": 0.08,
                        "service_z_ai": 1.65, "lost_sales": "lost (no backorders)", "margin": "list price − unit cost"},
    })
    daily.to_csv(run_.path / "daily.csv", index=False)
    per_rep.to_csv(run_.path / "replications.csv", index=False)
    registry.finalize(run_)
    r = results
    log(f"  fill rate {r['fill_rate']['baseline_mean']:.3f} -> {r['fill_rate']['ai_mean']:.3f}; "
        f"total cost {r['total_cost']['baseline_mean']:,.0f} -> {r['total_cost']['ai_mean']:,.0f} "
        f"(Δ {r['total_cost']['relative_change']:+.1%}); twin calibration fill {hist_fill:.3f} vs {calibration['twin_baseline_fill_rate']:.3f}")
    return run_


if __name__ == "__main__":
    run()
